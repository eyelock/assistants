// Every skill ships with evals (run via `pnpm test` / `node --test scripts/`).
// A skill needs evals/evals.json (output evals) and evals/eval_queries.json
// (trigger evals), in the agentskills.io format that scripts/skill-evals.mjs
// runs. Skills that predate the rule are listed in skills-without-evals.txt;
// that list only shrinks.

import assert from "node:assert/strict";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { armsFor, findOnPath, grade, plainChecks, seatLaunch, setupFor } from "./skill-evals.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const EXEMPT_FILE = join(ROOT, "scripts", "skills-without-evals.txt");

function findSkills(dir) {
  const found = [];
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name.startsWith(".")) continue;
    const path = join(dir, name);
    if (!statSync(path).isDirectory()) continue;
    if (existsSync(join(path, "SKILL.md"))) found.push(relative(ROOT, path));
    else found.push(...findSkills(path));
  }
  return found;
}

const skills = ["skills", "plugins"].flatMap((d) => findSkills(join(ROOT, d))).sort();
const exempt = new Set(
  readFileSync(EXEMPT_FILE, "utf8")
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#")),
);
const hasEvals = (s) =>
  existsSync(join(ROOT, s, "evals", "evals.json")) &&
  existsSync(join(ROOT, s, "evals", "eval_queries.json"));

test("every skill has output and trigger evals, unless it predates the rule", () => {
  const missing = skills.filter((s) => !hasEvals(s) && !exempt.has(s));
  assert.deepEqual(
    missing,
    [],
    "add evals/evals.json and evals/eval_queries.json (see AGENTS.md, Evals)",
  );
});

test("skills-without-evals.txt lists only skills that exist and still lack evals", () => {
  const stale = [...exempt].filter((s) => !skills.includes(s) || hasEvals(s));
  assert.deepEqual(stale, [], "remove these lines from scripts/skills-without-evals.txt");
});

for (const skill of skills.filter(hasEvals)) {
  test(`${skill}: evals are well formed`, () => {
    const name = skill.split("/").pop();
    const suite = JSON.parse(readFileSync(join(ROOT, skill, "evals", "evals.json"), "utf8"));
    assert.equal(suite.skill_name, name, "skill_name matches the skill directory");
    assert.ok(Array.isArray(suite.evals) && suite.evals.length > 0, "has at least one eval");
    const ids = suite.evals.map((c) => c.id);
    assert.equal(new Set(ids).size, ids.length, "eval ids are unique");
    for (const c of suite.evals) {
      const where = `eval ${c.id}`;
      assert.ok(typeof c.prompt === "string" && c.prompt.trim(), `${where}: has a prompt`);
      assert.ok(
        typeof c.expected_output === "string" && c.expected_output.trim(),
        `${where}: has an expected_output`,
      );
      assert.ok(
        Array.isArray(c.assertions) && (c.assertions.length > 0 || c.forbidden || c.required),
        `${where}: has assertions`,
      );
      // Call patterns are regular expressions that compile.
      for (const field of ["forbidden", "required"]) {
        for (const p of c[field] ?? []) {
          assert.doesNotThrow(() => new RegExp(p), `${where}: ${field} /${p}/ is a valid pattern`);
        }
      }
      // A tool whose calls the judge sees must be one the case grants.
      for (const t of c.tool_calls ?? []) {
        assert.ok((c.tools ?? []).includes(t), `${where}: tool_calls ${t} is granted in tools`);
      }
      // A case's own control is a script that exists, in its package.
      if (c.baseline_setup !== undefined) {
        const control = resolve(ROOT, skill, c.baseline_setup);
        assert.ok(c.setup, `${where}: baseline_setup is the control for a setup, so it needs one`);
        assert.ok(existsSync(control), `${where}: baseline_setup ${c.baseline_setup} exists`);
        assert.ok(
          control.startsWith(resolve(ROOT, skill, "..", "..")),
          `${where}: baseline_setup stays inside its package`,
        );
      }
      // A skill lives at <package>/skills/<name>; its fixtures stay in its package.
      const packageDir = resolve(ROOT, skill, "..", "..");
      for (const f of c.files ?? []) {
        const path = resolve(ROOT, skill, f);
        // Fixtures under a package's tests/fixtures/ are generated by its own scripts.
        if (path.includes("/tests/fixtures/")) continue;
        assert.ok(path.startsWith(packageDir), `${where}: ${f} stays inside its package`);
        assert.ok(existsSync(path), `${where}: file ${f} exists`);
      }
    }

    const queries = JSON.parse(
      readFileSync(join(ROOT, skill, "evals", "eval_queries.json"), "utf8"),
    );
    assert.ok(Array.isArray(queries), "eval_queries.json is an array");
    for (const q of queries) {
      assert.ok(typeof q.query === "string" && q.query.trim(), "every query has text");
      assert.equal(typeof q.should_trigger, "boolean", `"${q.query}": should_trigger is a boolean`);
    }
    assert.ok(
      queries.some((q) => q.should_trigger),
      "has at least one query that should trigger",
    );
    assert.ok(
      queries.some((q) => !q.should_trigger),
      "has at least one query that should not trigger",
    );
  });
}

test("setupFor: the with_skill arm runs the case's setup, with no control to report", () => {
  const c = { setup: "s.sh", baseline_setup: "b.sh" };
  assert.deepEqual(setupFor(c, "with_skill"), { script: "s.sh", control: null });
});

test("setupFor: without_skill runs the case's baseline_setup when it names one", () => {
  const c = { setup: "s.sh", baseline_setup: "b.sh" };
  assert.deepEqual(setupFor(c, "without_skill"), { script: "b.sh", control: "baseline_setup" });
});

test("setupFor: with no baseline_setup, without_skill keeps the setup, plugin hidden", () => {
  assert.deepEqual(setupFor({ setup: "s.sh" }, "without_skill"), {
    script: "s.sh",
    control: "plugin hidden",
  });
  assert.deepEqual(setupFor({}, "without_skill"), { script: undefined, control: "plugin hidden" });
});

test("armsFor: a seat case has one arm, because the seat is under test and no skill is taken away", () => {
  assert.deepEqual(armsFor({ seat: "harnesses/worker" }, true), ["with_skill"]);
  assert.deepEqual(armsFor({}, true), ["with_skill", "without_skill"]);
  assert.deepEqual(armsFor({}, false), ["with_skill"]);
});

test("seatLaunch: ynh run in a scratch home, the run's directory the only workspace root", () => {
  const work = mkdtempSync(join(tmpdir(), "seat-launch-test-"));
  try {
    const root = realpathSync(work);
    const launch = seatLaunch(
      { seat: "harnesses/worker", prompt: "hi" },
      "claude",
      work,
      { A: "1" },
      ["-p", "hi", "--max-turns", "3"],
    );
    assert.match(launch.cmd, /ynh$/);
    assert.deepEqual(launch.args, [
      "run",
      join(root, "harnesses/worker"),
      "-v",
      "claude",
      "--",
      "-p",
      "hi",
      "--max-turns",
      "3",
    ]);
    assert.equal(launch.env.YNH_HOME, join(root, ".eval", "ynh-home"));
    assert.equal(launch.env.YNH_WORKSPACE_ROOTS, root);
    assert.equal(launch.env.A, "1");
    assert.ok(!launch.args.includes("trust"), "never runs ynh trust accept");
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
});

test("seatLaunch: another vendor gets only the prompt, and an absolute seat path is kept", () => {
  const work = mkdtempSync(join(tmpdir(), "seat-launch-test-"));
  try {
    const launch = seatLaunch({ seat: "/abs/seat", prompt: "hi" }, "codex", work, {}, [
      "--claude-only",
    ]);
    assert.deepEqual(launch.args, ["run", "/abs/seat", "-v", "codex", "--", "-p", "hi"]);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
});

test("findOnPath: finds an executable on the given PATH, in order, and null when absent", () => {
  const a = mkdtempSync(join(tmpdir(), "path-a-"));
  const b = mkdtempSync(join(tmpdir(), "path-b-"));
  try {
    writeFileSync(join(b, "tool"), "#!/bin/sh\n", { mode: 0o755 });
    writeFileSync(join(a, "plain"), "x", { mode: 0o644 });
    assert.equal(findOnPath("tool", `${a}:${b}`), join(b, "tool"));
    assert.equal(findOnPath("plain", `${a}:${b}`), null);
    assert.equal(findOnPath("missing", `${a}:${b}`), null);
  } finally {
    rmSync(a, { recursive: true, force: true });
    rmSync(b, { recursive: true, force: true });
  }
});

test("plainChecks: a case with neither forbidden nor required has no plain checks", () => {
  assert.deepEqual(plainChecks({}, "gh pr merge 1"), []);
});

test("plainChecks: a forbidden call fails and names the call", () => {
  const r = plainChecks({ forbidden: ["^gh pr merge"] }, "gh pr view 1\ngh pr merge 1 --squash\n");
  assert.equal(r.length, 1);
  assert.equal(r[0].passed, false);
  assert.match(r[0].evidence, /gh pr merge 1 --squash/);
});

test("plainChecks: a forbidden pattern no call matches passes", () => {
  const r = plainChecks({ forbidden: ["^git stash"] }, "git status\n");
  assert.equal(r[0].passed, true);
});

test("plainChecks: a required call that appears passes, one that does not fails", () => {
  const calls = "git worktree add /tmp/w\n";
  const r = plainChecks({ required: ["^git worktree add", "^git commit"] }, calls);
  assert.deepEqual(
    r.map((x) => x.passed),
    [true, false],
  );
  assert.match(r[1].evidence, /no logged call matches/);
});

test("plainChecks: an empty log fails every required pattern and no forbidden one", () => {
  const r = plainChecks({ forbidden: ["^gh"], required: ["^bd close"] }, "");
  assert.deepEqual(
    r.map((x) => x.passed),
    [true, false],
  );
});

// grade() with a fake `claude` first on PATH that records each call it gets.
async function gradeWithFakeJudge(c, calls) {
  const dir = mkdtempSync(join(tmpdir(), "grade-test-"));
  const judgeLog = join(dir, "judge.log");
  const bin = join(dir, "bin");
  mkdirSync(bin);
  writeFileSync(
    join(bin, "claude"),
    `#!/bin/sh\necho called >> "${judgeLog}"\necho '{"structured_output":{"assertion_results":[{"passed":true,"evidence":"ok"}]}}'\n`,
  );
  chmodSync(join(bin, "claude"), 0o755);
  const oldPath = process.env.PATH;
  process.env.PATH = `${bin}:${oldPath}`;
  try {
    const ctx = { iterationDir: join(dir, "it"), runs: 1, judgeModel: "x" };
    mkdirSync(join(ctx.iterationDir, `eval-${c.name}`, "with_skill"), { recursive: true });
    const grading = await grade(c, "with_skill", 1, "answer", "", ctx, calls);
    const judged = existsSync(judgeLog);
    return { grading, judged };
  } finally {
    process.env.PATH = oldPath;
  }
}

test("grade: a forbidden call fails the case with no judge call, and names the call", async () => {
  const c = { id: 1, name: "f", assertions: ["says why"], forbidden: ["^gh pr merge"] };
  const { grading, judged } = await gradeWithFakeJudge(c, "gh pr merge 9\n");
  assert.equal(judged, false);
  assert.equal(grading.plain_check_failed, true);
  assert.equal(grading.summary.passed, 0);
  assert.match(grading.assertion_results[0].evidence, /gh pr merge 9/);
  assert.equal(grading.assertion_results[1].evidence, "not graded: a plain check failed");
});

test("grade: a missing required call fails the case with no judge call", async () => {
  const c = { id: 2, name: "r", assertions: ["says why"], required: ["^git worktree add"] };
  const { grading, judged } = await gradeWithFakeJudge(c, "git status\n");
  assert.equal(judged, false);
  assert.equal(grading.summary.failed, 2);
});

test("grade: when the plain checks pass, the judge grades the soft assertions", async () => {
  const c = { id: 3, name: "p", assertions: ["says why"], forbidden: ["^gh pr merge"] };
  const { grading, judged } = await gradeWithFakeJudge(c, "gh pr view 9\n");
  assert.equal(judged, true);
  assert.equal(grading.plain_check_failed, false);
  assert.equal(grading.summary.passed, 2);
});
