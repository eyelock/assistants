// Every skill ships with evals (run via `pnpm test` / `node --test scripts/`).
// A skill needs evals/evals.json (output evals) and evals/eval_queries.json
// (trigger evals), in the agentskills.io format that scripts/skill-evals.mjs
// runs. Skills that predate the rule are listed in skills-without-evals.txt;
// that list only shrinks.

import assert from "node:assert/strict";
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const EXEMPT_FILE = join(ROOT, "scripts", "skills-without-evals.txt");

function findSkills(dir) {
  const found = [];
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name.startsWith(".")) continue;
    const path = join(dir, name);
    if (!statSync(path).isDirectory()) continue;
    if (existsSync(join(path, "SKILL.md"))) found.push(relative(ROOT, path));
    else found.push(...findSkills(path));
  }
  return found;
}

const skills = ["skills", "plugins"].flatMap((d) => findSkills(join(ROOT, d))).sort();
const exempt = new Set(
  readFileSync(EXEMPT_FILE, "utf8")
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#")),
);
const hasEvals = (s) =>
  existsSync(join(ROOT, s, "evals", "evals.json")) &&
  existsSync(join(ROOT, s, "evals", "eval_queries.json"));

test("every skill has output and trigger evals, unless it predates the rule", () => {
  const missing = skills.filter((s) => !hasEvals(s) && !exempt.has(s));
  assert.deepEqual(
    missing,
    [],
    "add evals/evals.json and evals/eval_queries.json (see AGENTS.md, Evals)",
  );
});

test("skills-without-evals.txt lists only skills that exist and still lack evals", () => {
  const stale = [...exempt].filter((s) => !skills.includes(s) || hasEvals(s));
  assert.deepEqual(stale, [], "remove these lines from scripts/skills-without-evals.txt");
});

for (const skill of skills.filter(hasEvals)) {
  test(`${skill}: evals are well formed`, () => {
    const name = skill.split("/").pop();
    const suite = JSON.parse(readFileSync(join(ROOT, skill, "evals", "evals.json"), "utf8"));
    assert.equal(suite.skill_name, name, "skill_name matches the skill directory");
    assert.ok(Array.isArray(suite.evals) && suite.evals.length > 0, "has at least one eval");
    const ids = suite.evals.map((c) => c.id);
    assert.equal(new Set(ids).size, ids.length, "eval ids are unique");
    for (const c of suite.evals) {
      const where = `eval ${c.id}`;
      assert.ok(typeof c.prompt === "string" && c.prompt.trim(), `${where}: has a prompt`);
      assert.ok(
        typeof c.expected_output === "string" && c.expected_output.trim(),
        `${where}: has an expected_output`,
      );
      assert.ok(Array.isArray(c.assertions) && c.assertions.length > 0, `${where}: has assertions`);
      // A skill lives at <package>/skills/<name>; its fixtures stay in its package.
      const packageDir = resolve(ROOT, skill, "..", "..");
      for (const f of c.files ?? []) {
        const path = resolve(ROOT, skill, f);
        // Fixtures under a package's tests/fixtures/ are generated by its own scripts.
        if (path.includes("/tests/fixtures/")) continue;
        assert.ok(path.startsWith(packageDir), `${where}: ${f} stays inside its package`);
        assert.ok(existsSync(path), `${where}: file ${f} exists`);
      }
    }

    const queries = JSON.parse(
      readFileSync(join(ROOT, skill, "evals", "eval_queries.json"), "utf8"),
    );
    assert.ok(Array.isArray(queries), "eval_queries.json is an array");
    for (const q of queries) {
      assert.ok(typeof q.query === "string" && q.query.trim(), "every query has text");
      assert.equal(typeof q.should_trigger, "boolean", `"${q.query}": should_trigger is a boolean`);
    }
    assert.ok(
      queries.some((q) => q.should_trigger),
      "has at least one query that should trigger",
    );
    assert.ok(
      queries.some((q) => !q.should_trigger),
      "has at least one query that should not trigger",
    );
  });
}
